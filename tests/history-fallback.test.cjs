const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const dataJs = fs.readFileSync(require.resolve('../assets/history-data.js'), 'utf8');
const app = fs.readFileSync(require.resolve('../assets/app.js'), 'utf8');
const html = fs.readFileSync(require.resolve('../index.html'), 'utf8');
const context = { window: {}, globalThis: {} };
vm.runInNewContext(dataJs, context);
const data = context.window.M539BundledHistory;
assert.equal(data.length, 200);
assert.equal(data[0].period, '115000269');
assert.deepEqual(Array.from(data[0].numbers), [14, 20, 23, 26, 29]);
assert.match(app, /function getStartIndex\(period\)/);
assert.match(app, /draws = getBundledHistory\(\);[\s\S]*?renderDrawOptions\(\);[\s\S]*?refreshData\(false\);/);
assert.match(app, /即時資料更新失敗，目前使用/);
assert.match(app, /背景仍在嘗試更新即時資料/);
assert.match(app, /generateBtn'\)\.disabled = !eligible/);
assert.match(html, /程式載入逾時/);
console.log('PASS: bundled 200-draw fallback, startup index resolver and loader watchdog are present.');
