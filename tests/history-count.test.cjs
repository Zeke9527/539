const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync(require.resolve('../assets/app.js'), 'utf8');
const html = fs.readFileSync(require.resolve('../index.html'), 'utf8');
assert.match(app, /const HISTORY_COUNT = 200;/);
assert.match(app, /const PICKER_COUNT = 36;/);
assert.match(app, /historyWindow: 36/);
assert.match(app, /const count = 5;/);
assert.match(app, /m539-final-v7-5-draw-cache/);
assert.match(html, /最近36期/);
assert.match(html, /固定選出5碼/);
assert.doesNotMatch(html, /id="numberCount"|id="historyWindow"/);
console.log('PASS: v7.5 displays 36 draws, trains on 36, excludes four and outputs five.');
