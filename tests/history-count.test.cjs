const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync(require.resolve('../assets/app.js'), 'utf8');
const html = fs.readFileSync(require.resolve('../index.html'), 'utf8');
assert.match(app, /const HISTORY_COUNT = 200;/);
assert.match(app, /const PICKER_COUNT = 15;/);
assert.match(app, /const DEFAULT_HISTORY_WINDOW = 12;/);
assert.match(app, /historyWindow: selectedHistoryWindow/);
assert.match(app, /const count = 5;/);
assert.match(app, /m539-final-v7-6-draw-cache/);
assert.match(html, /最近15期/);
assert.match(html, /id="historyWindow"/);
assert.match(html, /value="12"/);
assert.match(html, /value="18"/);
assert.match(html, /固定選出5碼/);
assert.doesNotMatch(html, /最近36期/);
console.log('PASS: v7.6 displays 15 draws, allows 12/18 history windows, excludes four and outputs five.');
